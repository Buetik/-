def add(id_, room, name, type_, rect, h, rot=0, z=0, custom=False, power=None, water=False, drain=False,
        low=None, water_spec=None, drain_spec=None, note="", layer="floor", t=None, lab=None, module=None,
        manifold_access=False, allow=()):
    x1, y1, x2, y2 = rect
    bw, bd = x2 - x1, y2 - y1
    w, d = (bw, bd) if rot in (0, 180) else (bd, bw)
    it = {"id": id_, "room": room, "name": name, "type": type_, "pos": [x1, y1], "size": [w, d, h],
          "rotation": rot, "custom": custom,
          "needs": {"power": power or [], "water": water, "drain": drain}}
    if low:
        it["needs"]["low_current"] = low
    if water_spec:
        it["needs"]["water_spec"] = water_spec
    if drain_spec:
        it["needs"]["drain_spec"] = drain_spec
    if z:
        it["z"] = z
    it["layer"] = layer
    if module:
        it["module"] = module
    if note:
        it["note"] = note
    if manifold_access:
        it["manifold_access"] = True
    it["_draw"] = {"t": t or {"bed": "bed", "sofa": "sofa", "wardrobe": "tall", "kitchen_base": "kitchen", "kitchen_wall": "kitchen",
                              "appliance": "wm", "table": "table", "chair": "chair", "sanitary": "sink", "other": "dresser"}[type_],
                   "l": lab if lab is not None else "", "allow": list(allow)}
    ITEMS.append(it)
    return it


