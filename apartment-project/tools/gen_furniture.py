def rect_of(it):
    x, y = it["pos"]
    w, d, _ = it["size"]
    bw, bd = (w, d) if it["rotation"] in (0, 180) else (d, w)
    return x, y, x + bw, y + bd


def ov(a, b):
    return max(0, min(a[2], b[2]) - max(a[0], b[0])) * max(0, min(a[3], b[3]) - max(a[1], b[1]))


def zr(it):
    z = it.get("z", 0)
    return z, z + it["size"][2]


def zov(a, b):
    a1, a2 = zr(a)
    b1, b2 = zr(b)
    return min(a2, b2) > max(a1, b1)


def inside(it, poly):
    x1, y1, x2, y2 = rect_of(it)
    pts = [(x1 + 1, y1 + 1), (x2 - 1, y1 + 1), (x2 - 1, y2 - 1), (x1 + 1, y2 - 1)]
    return all(pin(p, poly) for p in pts)


def pin(pt, poly):
    x, y = pt
    ins = False
    for (x1, y1), (x2, y2) in zip(poly, poly[1:] + poly[:1]):
        if (y1 > y) != (y2 > y) and x1 + (y - y1) * (x2 - x1) / (y2 - y1) > x:
            ins = not ins
    return ins


