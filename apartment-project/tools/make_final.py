def pin(pt, poly):
    x, y = pt
    ins = False
    for (x1, y1), (x2, y2) in zip(poly, poly[1:] + poly[:1]):
        if (y1 > y) != (y2 > y) and x1 + (y - y1) * (x2 - x1) / (y2 - y1) > x:
            ins = not ins
    return ins


def overlap(p, q):
    xs = sorted({v[0] for v in p + q}); ys = sorted({v[1] for v in p + q}); s = 0
    for i in range(len(xs) - 1):
        for j in range(len(ys) - 1):
            c = ((xs[i] + xs[i + 1]) / 2, (ys[j] + ys[j + 1]) / 2)
            if pin(c, p) and pin(c, q):
                s += (xs[i + 1] - xs[i]) * (ys[j + 1] - ys[j])
    return s


def rect_poly(r):
    x1, y1, x2, y2 = r
    return [[x1, y1], [x2, y1], [x2, y2], [x1, y2]]


