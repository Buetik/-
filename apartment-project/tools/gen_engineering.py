def heat_area(room_rect, excl, margin=100, ex_margin=50):
    x1, y1, x2, y2 = room_rect
    xs = np.arange(x1 + 5, x2, 10)
    ys = np.arange(y1 + 5, y2, 10)
    X, Y = np.meshgrid(xs, ys)
    m = (X > x1 + margin) & (X < x2 - margin) & (Y > y1 + margin) & (Y < y2 - margin)
    for (a, b, c, d, *mm) in excl:
        e = mm[0] if mm else ex_margin
        m &= ~((X > a - e) & (X < c + e) & (Y > b - e) & (Y < d + e))
    return round(m.sum() * 100 / 1e6, 2), m, xs, ys


