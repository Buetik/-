def small_fan_loss(q, L, bends, d=0.1):
    A = math.pi * d * d / 4
    v = q / 3600 / A
    pd = RHO * v * v / 2
    return round(lam(d, v) / d * L * pd + (bends * 0.35 + 1.5 + 1.0) * pd, 1), round(v, 1)


