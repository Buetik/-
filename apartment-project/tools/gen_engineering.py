RHO, NU = 1.2, 15e-6


def lam(d, v, k=0.0001):
    re = v * d / NU
    return 0.11 * (k / d + 68 / re) ** 0.25


def duct_loss(q, kind):
    """Потери давления трассы вытяжки (Па) при расходе q, м³/ч. Трасса ≈ 4,05 м."""
    L = 4.05
    if kind == "d125":
        A, dh, z_el = math.pi * 0.125 ** 2 / 4, 0.125, 0.35
        z_loc = 0.3 + 3 * z_el + 2 * 0.15 + 1.5   # переход от вытяжки, 3 отвода 90°, 2×45° (опуск к решётке), обратный клапан
    elif kind == "d150":
        A, dh, z_el = math.pi * 0.150 ** 2 / 4, 0.150, 0.35
        z_loc = 0.3 + 3 * z_el + 2 * 0.15 + 1.5 + 0.3  # + переход 150→125 у решётки
    else:  # плоский 204×60
        A, dh, z_el = 0.204 * 0.060, 2 * 0.204 * 0.060 / (0.204 + 0.060), 0.6
        z_loc = 0.3 + 2 * 0.2 + 3 * z_el + 2 * 0.3 + 1.5  # + 2 перехода круг/плоский, плоские отводы
    v = q / 3600 / A
    pd = RHO * v * v / 2
    fr = lam(dh, v) / dh * L * pd
    # вход в канал: отверстие в W10 ≈ 100×150 (U13) — сужение + выход в канал, ζ≈2 по скорости в отверстии
    v_o = q / 3600 / (0.10 * 0.15)
    p_o = 2.0 * RHO * v_o * v_o / 2
    return round(fr + z_loc * pd + p_o, 1), round(v, 1), round(v_o, 1)


def hood_point(kind, qmax=600, pmax=450):
    """Рабочая точка вытяжки (паспорт: 600 м³/ч свободный выдув, ≈ 450 Па макс.) — линейная аппроксимация кривой."""
    lo, hi = 0.0, qmax
    for _ in range(60):
        q = (lo + hi) / 2
        if pmax * (1 - q / qmax) > duct_loss(q, kind)[0]:
            lo = q
        else:
            hi = q
    return round(lo)


