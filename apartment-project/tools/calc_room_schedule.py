"""Экспликация помещений (ОД-04) — расчёт площадей скриптом. Владелец: pib-chief-architect.

Читает только: 01-input/measurements.json (полигоны застройщика), 03-drawings/planning.json (полигоны D1).
Пишет: 04-specs/room-schedule.md.

Площади:
  S_base   — по внутренним граням стен/перегородок до отделки (полигоны planning.json), как в техплане;
  S_finish — по чистовой отделке (оценка): полигон, уменьшенный на толщину отделки стен, минус
             облицовки и короба стояков. Толщины — [ДОПУЩЕНИЕ] (FINISH ниже), уточняются обмером.
Запуск: python3 apartment-project/tools/calc_room_schedule.py
"""
import json
from pathlib import Path

from shapely.geometry import Polygon, box

ROOT = Path(__file__).resolve().parents[1]
M = json.loads((ROOT / "01-input/measurements.json").read_text(encoding="utf-8"))
P = json.loads((ROOT / "03-drawings/planning.json").read_text(encoding="utf-8"))

# Площади по плану застройщика (подписи PDF), м²
DEV = {"R1": 17.79, "R2": 11.97, "R3": 14.20, "R4": 9.50, "R5": 5.38, "R6": 3.36, "R7": 6.81}
ORDER = ["R1", "R2", "R3", "R4", "R5", "R6", "R7"]  # = ROOM_NO в tools/model.py
NO = {r: i + 1 for i, r in enumerate(ORDER)}

# Высота от УЧП (±0.000 = плита +100) до чистового потолка, мм — по D19 / ceilings.json
HEIGHT = {
    "R1": "2700",
    "R2": "2700",
    "R3": "2650 (короба: CB-1 2400, CB-2 2290, ламбрекен CB-3 2550)",
    "R4": "2650",
    "R5": "2450 (пол ванной ±0.000 в уровень, D26)",
    "R6": "2500",
    "R7": "2500 [ДОПУЩЕНИЕ №51]",
}
CATEGORY = {"R1": "жилая", "R2": "жилая", "R3": "вспомогательная (кухня)", "R4": "вспомогательная",
            "R5": "мокрая", "R6": "мокрая", "R7": "летнее (балкон, к=0,3), тёплый контур"}

# [ДОПУЩЕНИЕ] отделка стен по контуру, мм: штукатурка+шпаклёвка 15; мокрые с плиткой 30 (выравнивание+клей+керамогранит)
FINISH = {"R1": 15, "R2": 15, "R3": 15, "R4": 15, "R5": 30, "R6": 15, "R7": 15}
# Дополнительные вычеты (облицовки, утепление, короба), прямоугольники x0,y0,x1,y1, мм
EXTRA = {
    "R1": [("облицовка W7 ГКЛ на профиле 55 (D23, НК-06) y 4820..8911", box(3325, 4820, 3380, 8911))],
    "R5": [("короб стояков U10 678×325", box(6863, 5516, 7541, 5841)),
           ("облицовка W14 в душе 95 (D18) y 4550..5516", box(7446, 4550, 7541, 5516))],
    "R6": [("короб стояков U5 305×681", box(4170, 0, 4475, 681))],
    "R7": [("утепление PIR/XPS + обшивка по остеклению/ограждению 100 (3 стороны)",
            Polygon([(-2531, -55), (-420, -55), (-420, 45), (-2431, 45), (-2431, 3068), (-420, 3068),
                     (-420, 3168), (-2531, 3168)]))],
}

# Разница с полигонами застройщика (measurements.json) — откуда «потерялась» площадь
WHY = {
    "R1": "проём O9 1770×140 в несущей W8 застройщик включил в комнату; по D1 он закладывается (NW1) и уходит в тело стены",
    "R2": "полоса 1300×81 (y 5970..6051) у коридора: по D1 здесь новая перегородка NW4",
    "R4": "проём O8 1099×140 в несущей W7: застройщик включил в коридор; по D1 в нём дверь D1 (тело стены)",
}


def area(g):
    return g.area / 1e6


def main():
    dev_poly = {r["id"]: Polygon(r["polygon"]) for r in M["rooms"]}
    from shapely.ops import unary_union
    # открытая граница кухня/прихожая (x=3810) — без стены: отделку вычитаем только по реальным стенам
    whole = unary_union([Polygon(x["polygon"]) for x in P["rooms"] if x["id"] != "R7"])
    rows, tot = [], {"base": 0, "fin": 0, "dev": 0, "lb": 0, "lf": 0, "ld": 0}
    recon = []
    for rid in ORDER:
        r = next(x for x in P["rooms"] if x["id"] == rid)
        g = Polygon(r["polygon"])
        sb = area(g)
        base = whole if rid in ("R3", "R4") else g
        gf = g.intersection(base.buffer(-FINISH[rid], join_style=2))
        notes = [f"отделка {FINISH[rid]}"]
        for txt, b in EXTRA.get(rid, []):
            gf = gf.difference(b)
            notes.append(txt)
        sf = area(gf)
        sd = DEV[rid]
        diff_dev = area(dev_poly[rid]) - sb
        rows.append((NO[rid], rid, r["name"], sb, sf, sd, HEIGHT[rid], CATEGORY[rid], "; ".join(notes)))
        if rid != "R7":
            tot["base"] += sb; tot["fin"] += sf; tot["dev"] += sd
            if rid in ("R1", "R2"):
                tot["lb"] += sb; tot["lf"] += sf; tot["ld"] += sd
        if abs(diff_dev) > 0.005:
            recon.append((rid, r["name"], sd, area(dev_poly[rid]), sb, diff_dev, WHY.get(rid, "")))

    f = lambda v: f"{v:.2f}".replace(".", ",")
    L = []
    L.append("# ОД-04. Экспликация помещений (итоговая, вариант D1)\n")
    L.append("Подсчёт — скриптом `tools/calc_room_schedule.py` по полигонам `03-drawings/planning.json` (D1) "
             "и `01-input/measurements.json`; на глаз ничего не считалось. Отметки — от УЧП ±0.000 (= верх плиты +100).\n")
    L.append("**База подсчёта.** Графа «S до отделки» — по внутренним граням стен и перегородок до отделки "
             "(как в техплане/БТИ, по геометрии плана застройщика ±20 мм — фактического обмера нет, З-06). "
             "Графа «S по чистовой отделке» — оценка: контур уменьшен на толщину отделки стен, вычтены облицовки, "
             "утепление балкона и короба стояков (толщины — [ДОПУЩЕНИЕ], см. примечание). "
             "Для техпаспорта/согласования действует S до отделки.\n")
    L.append("| № | Id | Наименование | S до отделки, м² | S по чистовой отделке, м² | S по плану застройщика, м² | "
             "Высота до чистового потолка, мм | Категория | Учтено в чистовой площади |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    for n, rid, name, sb, sf, sd, h, c, nt in rows:
        L.append(f"| {n} | {rid} | {name} | {f(sb)} | {f(sf)} | {f(sd)} | {h} | {c} | {nt} |")
    b7 = next(x for x in rows if x[1] == "R7")
    L.append(f"| | | **Итого без балкона** | **{f(tot['base'])}** | **{f(tot['fin'])}** | **{f(tot['dev'])}** | | | |")
    L.append(f"| | | в т.ч. жилая (R1+R2) | {f(tot['lb'])} | {f(tot['lf'])} | {f(tot['ld'])} | | | |")
    L.append(f"| | | Балкон с к=0,3 | {f(b7[3]*0.3)} | {f(b7[4]*0.3)} | 2,04 | | | |")
    L.append(f"| | | **Общая с балконом (к=0,3)** | **{f(tot['base']+b7[3]*0.3)}** | **{f(tot['fin']+b7[4]*0.3)}** | **64,24** | | | |")
    L.append(f"| | | Общая с балконом (к=1,0) | {f(tot['base']+b7[3])} | {f(tot['fin']+b7[4])} | 69,01 | | | |")
    L.append("")
    L.append("## Сверка с планом застройщика\n")
    L.append(f"Без балкона: {f(tot['dev'])} (застройщик) → {f(tot['base'])} м² (D1), разница "
             f"{f(tot['dev']-tot['base'])} м². Жилая: {f(tot['ld'])} → {f(tot['lb'])} м², разница {f(tot['ld']-tot['lb'])} м².\n")
    L.append("Полигоны застройщика (measurements.json) воспроизводят подписи плана с точностью до 0,01 м². "
             "Вся разница — это площадь проёмов в стенах и полоса под новой перегородкой, которые застройщик "
             "отнёс к помещениям. По D1 они уходят в тело стен или перегородок:\n")
    L.append("| Id | Помещение | По плану | Полигон застройщика | D1 | Разница | Причина |")
    L.append("|---|---|---|---|---|---|---|")
    for rid, name, sd, sp, sb, d, why in recon:
        L.append(f"| {rid} | {name} | {f(sd)} | {f(sp)} | {f(sb)} | −{f(d)} | {why} |")
    L.append("| R5 | Ванная | 5,38 | 5,39 | 5,39 | 0,00 | округление (2641×2041), площадь не меняется (D6) |")
    L.append("")
    L.append("Баланс: −0,25 − 0,11 − 0,15 = −0,51 м²; ванная по полигону на 0,01 больше подписи → итог −0,49 (≈ −0,50). "
             "Сумма округлённых строк D1 — 61,70 м² (как на ОД-04 предварительной), точная — 61,71 м².\n")
    L.append("Облицовки, гардероб и короба в разнице «застройщик → D1» не участвуют, потому что это отделка или мебель, "
             "а не границы помещений. Гардеробной-перегородки в спальне нет (D8). Их влияние показано отдельно, в графе «S по чистовой отделке».\n")
    L.append("## Примечания\n")
    L.append("1. Отделка стен [ДОПУЩЕНИЕ]: штукатурка + шпаклёвка 15 мм; в ванной — 30 мм (выравнивание + клей + "
             "керамогранит). Облицовка W7 спальни ГКЛ на профиле — 55 мм (геометрию задаёт pib-planning, НК-06). "
             "Облицовка W14 в душе — 95 мм (D18). Утепление балкона — 100 мм по остеклению/ограждению с трёх сторон "
             "(оценка planning.json). Буазери (≈20 мм) и встроенная мебель в площадь не входят.")
    L.append("2. Балкон после утепления остаётся балконом (летнее помещение, к=0,3) до внесения изменений в техплан по "
             "согласованному проекту перепланировки (З-09).")
    L.append("3. Ванная: чистовой пол ±0.000 в уровень с квартирой, порог D3 = 0 (D26); локальное понижение в зоне душа "
             "к трапу — уклон 1,5 %. Запасное решение — подиум +80 (D18).")
    L.append("4. Нумерация помещений совпадает с листами АР (R1 = 1 … R7 = 7). Граница кухня/прихожая (x = 3810) — "
             "условная, без стены (questions №45); по ней отделка не вычитается.")
    out = ROOT / "04-specs/room-schedule.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(out)
    for r in rows:
        print(r[:6])
    print({k: round(v, 3) for k, v in tot.items()})


if __name__ == "__main__":
    main()
