def pts_of(cid):
    out = []
    for s in SOCKETS:
        if s["circuit"] == cid and not str(s["wall"]).startswith(("торец", "отсек")):
            out.append((s["pos"], s["height"]))
    for l in LIGHTS:
        if LGROUP_CIRCUIT[l["group"]] == cid:
            out.append((l["pos"], l["height"]))
    for sw in SWITCHES:
        if any(LGROUP_CIRCUIT.get(c.split("+")[0]) == cid for c in sw["controls"]):
            out.append((sw["pos"], sw["height"]))
    return out


def route_len(points):
    """Оценка трассы: щит (верх +2110) → потолок → обход точек (ближайший сосед) по потолку манхэттеном,
    к каждой точке спуск и подъём (шлейф), +10 % + 1,5 м на разделку."""
    if not points:
        return 0
    cur = PANEL_POS
    tot = (CEIL - 2110)
    rest = list(points)
    while rest:
        rest.sort(key=lambda p: abs(p[0][0] - cur[0]) + abs(p[0][1] - cur[1]))
        p, h = rest.pop(0)
        tot += abs(p[0] - cur[0]) + abs(p[1] - cur[1])
        tot += (CEIL - h) * (2 if rest else 1)
        cur = p
    return round(tot / 1000 * 1.1 + 1.5, 1)


