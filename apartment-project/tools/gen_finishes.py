def elev(room, wall_id, title, axis, s0, s1, z0, z1, view, items, tile=None, finish=None, sheet="", left=None, face=None):
    d = {"room": room, "wall_id": wall_id, "title": title, "sheet": sheet, "axis": axis, "span": [s0, s1],
         "z": [z0, z1], "view": view, "finish": finish or [], "tile": tile, "items": items}
    if left is not None:
        d["left"] = left
    if face is not None:
        d["face"] = face
    E.append(d)


def it(kind, name, s, z, **kw):
    d = {"type": kind, "name": name, "s": [round(s[0]), round(s[1])], "z": [round(z[0]), round(z[1])]}
    d.update(kw)
    return d


def pt(kind, name, s, z, **kw):
    d = {"type": kind, "name": name, "s": round(s), "z": round(z)}
    d.update(kw)
    return d


