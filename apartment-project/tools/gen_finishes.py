def herringbone(a, b, anchor, mode, L=600):
    """полосы ёлочки ширина L·cos45 + ... упрощённо: шаг полосы 2·L·cos45 = 848; mode='edge'|'center'"""
    step = 2 * L * math.cos(math.radians(45))
    start = anchor if mode == "edge" else anchor - step / 2
    k = math.floor((a - start) / step)
    edges = []
    x = start + k * step
    while x < b + step:
        if a < x < b:
            edges.append(round(x))
        x += step
    cuts = [round(edges[0] - a), round(b - edges[-1])] if edges else [b - a]
    return {"stripe_mm": round(step), "edges": edges, "edge_cuts": cuts, "cut_ratio": [round(c / step, 2) for c in cuts]}


def best_hb(a, b, anchor=None, force=None):
    c = (a + b) / 2 if anchor is None else anchor
    opts = []
    for mode in ((force,) if force else ("edge", "center")):
        h = herringbone(a, b, c, mode)
        opts.append((min(h["cut_ratio"]), mode, h))
    opts.sort(key=lambda t: -t[0])
    _, mode, h = opts[0]
    h["mode"] = mode
    h["anchor"] = round(c)
    return h


def tiles_1d(a, b, joint_at, step):
    """швы с шагом step через точку joint_at в пределах [a, b]"""
    k = math.floor((a - joint_at) / step)
    j = []
    x = joint_at + k * step
    while x <= b:
        if a < x < b:
            j.append(round(x, 1))
        x += step
    pieces = [round(t - s, 1) for s, t in zip([a] + j, j + [b])]
    return {"joints": j, "pieces": pieces, "min_ratio": round(min(pieces) / step, 2)}


