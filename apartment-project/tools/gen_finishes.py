def rect_of(it):
    x, y = it["pos"]
    w, d = it["size"][0], it["size"][1]
    if it["rotation"] in (90, 270):
        w, d = d, w
    return [x, y, x + w, y + d]


def poly_area(p):
    return abs(sum(p[i][0] * p[(i + 1) % len(p)][1] - p[(i + 1) % len(p)][0] * p[i][1] for i in range(len(p)))) / 2e6


def rarea(r):
    return (r[2] - r[0]) * (r[3] - r[1]) / 1e6


def inside(pt, r):
    return r[0] <= pt[0] <= r[2] and r[1] <= pt[1] <= r[3]


def r2(v):
    return round(v + 1e-9, 2)


