def main():
    out = ROOT / "03-drawings"
    (out / "svg").mkdir(exist_ok=True)
    sel = sys.argv[1:] or list(OPTIONS)
    for k, o in OPTIONS.items():
        if k not in sel:
            continue
        HINTS = ("closed_openings", "cut_openings", "extra_openings_on_new", "demolished_walls",
                 "door_arcs", "revisions", "label_pos", "label_fs", "infill_draw", "corridor_w", "plan_note")
        data = {kk: vv for kk, vv in o.items() if kk not in HINTS}
        data["drawing_hints"] = {kk: o.get(kk) for kk in HINTS if kk in o}
        data["units"] = "mm"
        data["source"] = "01-input/measurements.json (id стен/проёмов/инженерии); превью 03-drawings/svg/planning-option-%s.png" % k
        data["furniture"] = [{"type": f["t"], "rect": [[f["r"][0], f["r"][1]], [f["r"][2], f["r"][3]]], "label": f["l"].replace("\n", " ")} for f in o["furniture"]]
        (out / f"planning-option-{k}.json").write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
        draw(o, out / "svg" / f"planning-option-{k}.png")
        print(k, o["areas"], [(r["id"], r["name"], r["area"]) for r in o["rooms"]])
    return OPTIONS


if __name__ == "__main__":
    main()
