def keo_side(win, point, H=None, D=None, n=200, tau=0.54, kz=1.2, ro=2.0, bf=0.15):
    """КЕО при боковом освещении в точке на полу (СП 52.13330.2016, принцип расчёта e = (ε_б·q + ε_зд·b_ф)·r_o·τ_o/K_з).
    ε_б·q — численное интегрирование яркости неба МКО (пасмурное, L ∝ (1+2 sin θ)/3) через проём с учётом толщины стены
    (луч проходит и внутреннюю, и наружную грань проёма); противостоящее здание — бесконечная стена высотой H (м над полом
    комнаты) на расстоянии D (м) от наружной грани, его фасад — b_ф. win = (x0, x1, z0, z1, y_in, y_out), окно в стене y=const."""
    import math
    x0, x1, z0, z1, yi, yo = win
    px, py, pz = point
    sky = bld = 0.0
    for i in range(n):
        th = (i + 0.5) / n * math.pi / 2
        for j in range(2 * n):
            ph = -math.pi / 2 + (j + 0.5) / (2 * n) * math.pi
            dx, dy, dz = math.cos(th) * math.sin(ph), math.cos(th) * math.cos(ph), math.sin(th)
            ok = True
            for yy in (yi, yo):
                t = (yy - py) / dy
                if not (x0 <= px + dx * t <= x1 and z0 <= pz + dz * t <= z1):
                    ok = False
                    break
            if not ok:
                continue
            w = math.sin(th) * math.cos(th) * (math.pi / 2 / n) * (math.pi / (2 * n))
            if H is not None and th < math.atan2(H * 1000, (D * 1000 + (yo - py)) / math.cos(ph)):
                bld += w / math.pi
            else:
                sky += (1 + 2 * math.sin(th)) / 3 * w * 9 / (7 * math.pi)
    return round((sky + bld * bf) * ro * tau / kz * 100, 2)


