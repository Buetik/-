def area(poly):
    s = 0
    for (x1, y1), (x2, y2) in zip(poly, poly[1:] + poly[:1]):
        s += x1 * y2 - x2 * y1
    return abs(s) / 2e6


def wall_rect(a, b, t):
    (x1, y1), (x2, y2) = a, b
    if y1 == y2:
        return min(x1, x2), y1 - t / 2, abs(x2 - x1), t
    return x1 - t / 2, min(y1, y2), t, abs(y2 - y1)


def opening_rect(wall, offset, width):
    a, b, t = wall["a"], wall["b"], wall["thickness"]
    if a[1] == b[1]:
        x0 = min(a[0], b[0]) + offset
        return x0, a[1] - t / 2 - 2, width, t + 4, "h"
    y0 = min(a[1], b[1]) + offset
    return a[0] - t / 2 - 2, y0, t + 4, width, "v"


